import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

// Dependency injection for a standalone local SQL check; no application code
// imports another repository. Pass an installed PGlite module path or install it locally.
const modulePath = process.argv[2];
const { PGlite } = await import(modulePath ? pathToFileURL(path.resolve(modulePath)).href : '@electric-sql/pglite');
const db = new PGlite();
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create schema app;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema public,auth,app to anon,authenticated,service_role;
    create table public.platform_admins(user_id uuid primary key references auth.users(id),
      granted_at timestamptz default now(),revoked_at timestamptz,role text default 'platform_owner',status text default 'active');
    insert into auth.users values('00000000-0000-4000-8000-000000000001');
    insert into public.platform_admins(user_id) select id from auth.users;
    create function app.is_platform_admin() returns boolean language sql security definer
      set search_path=public,pg_temp as $$ select exists(select 1 from platform_admins where user_id=auth.uid() and revoked_at is null and status='active') $$;
    create function app.platform_admin_role() returns text language sql security definer
      set search_path=public,pg_temp as $$ select role from platform_admins where user_id=auth.uid() and revoked_at is null and status='active' $$;
    create table public.admin_audit_log(id bigint generated by default as identity primary key,admin_id uuid,action text,detail jsonb,at timestamptz default now());
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/1021_book_demo_foundation.sql', import.meta.url),'utf8'));
  await db.exec(await readFile(new URL('../supabase/apply/1021_verify.sql', import.meta.url),'utf8'));
  const { rows } = await db.query(`select relname,relrowsecurity,relforcerowsecurity from pg_class
    where relname in ('platform_sales_leads','platform_sales_activities','platform_demo_requests','platform_demo_working_hours','platform_demo_day_overrides')`);
  assert.equal(rows.length,5);
  assert.ok(rows.every(r=>r.relrowsecurity && r.relforcerowsecurity));
  for (const role of ['anon','authenticated']) {
    const { rows: privileges } = await db.query(`select relname from pg_class where relname in
      ('platform_sales_leads','platform_sales_activities','platform_demo_requests','platform_demo_working_hours','platform_demo_day_overrides')
      and relkind='r' and has_table_privilege($1,oid,'SELECT,INSERT,UPDATE,DELETE')`,[role]);
    assert.equal(privileges.length,0);
  }
  assert.equal((await db.query('select count(*)::integer as n from public.platform_sales_leads')).rows[0].n,0);
  console.log('Book Demo SQL checks passed; all verification fixtures rolled back.');
} catch (error) {
  console.error('Book Demo SQL check failed:', error.message, error.code ?? '', error.where ?? '', error.position ?? '');
  process.exitCode = 1;
} finally { await db.close(); }
